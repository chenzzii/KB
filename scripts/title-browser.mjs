import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
// v1.3: title → story (skip / read) → role selection → journey, first-time tips shown once, map role markers.
const url=process.env.SMOKE_URL||'http://127.0.0.1:5173/';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1400,height:900}});
const page=await context.newPage(),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});page.on('console',m=>{if(m.type()==='error')errors.push(m.text()+' '+(m.location()?.url??''));});
const check=(name,ok,detail='')=>{checks.push({name,ok:!!ok,detail});if(!ok)console.error('FAIL',name,detail);};
const closeTips=async()=>{const seen=[];while(await page.locator('.tip-layer').count()){seen.push(await page.locator('.tip-layer').getAttribute('data-tip'));await page.locator('#tip-ok').click();}return seen;};
await mkdir('artifacts',{recursive:true});
await page.goto(url);
await page.locator('.title-screen #title-new').waitFor();
check('title screen shown first',await page.locator('.title-screen h1').textContent()==='九州兵譜');
check('no continue without save',await page.locator('#title-continue').count()===0);
check('no tip above title',await page.locator('.tip-layer').count()===0);
await page.locator('#title-help').click();check('help dialog',await page.locator('.title-help dt').count()>=6);await page.locator('#help-close').click();
await page.locator('#title-new').click();
let pages=1;while((await page.locator('#story-next').textContent())!=='選擇身分'){await page.locator('#story-next').click();pages++;}
check('story has five pages',pages===5,String(pages));
await page.locator('#story-next').click();
check('role selection after story',await page.locator('.hero-card').count()===4);
await page.locator('#select-story').click();await page.locator('#story-skip').click();
check('story can be skipped',await page.locator('.hero-card').count()===4);
for(const id of ['wu_jiang','ru_jiang','hao_xia','fang_shi']){await page.locator(`[data-hero="${id}"]`).click();check(`hero ${id} detail`,(await page.locator('.hero-traits li').count())===3&&(await page.locator('.hero-army > span').count())>=1);}
await page.locator('[data-hero="hao_xia"]').click();
const toggleCount=await page.locator('.title-settings input[type=checkbox]').count();check('settings toggles',toggleCount===5,String(toggleCount));
await page.locator('#opt-sfx').uncheck();
await page.locator('#title-start').click();
check('title closed',await page.locator('.title-screen').count()===0);
check('chosen hero applied',(await page.locator('.journey-header').textContent()).includes('豪俠'));
check('sfx setting applied',(await page.locator('#campaign-sound').textContent()).includes('關'));
const first=await closeTips();
check('first tips shown',first.includes('map')&&first.includes('home'),first.join(','));
const roles=await page.locator('[data-place-role]').evaluateAll(els=>els.map(e=>e.dataset.placeRole));
check('recruit sites marked',roles.filter(r=>r==='recruit').length>=2,roles.join(','));
check('legend present',await page.locator('.marker-legend .k-battle').count()===1);
// v1.5: the quest starts accepted; there is no 接受委託 button.
check('no accept-quest step',await page.locator('[data-action="accept"]').count()===0);
await page.locator('[data-destination="7,5"]').click();
await page.waitForFunction(()=>document.querySelector('.location-panel h3')?.textContent?.includes('柳灣鄉營'));
await page.waitForTimeout(200);
const camp=await closeTips();check('camp tip on first arrival',camp.includes('camp'),camp.join(','));
check('camp labelled recruit',await page.locator('.location-panel .place-kind.kp-recruit').count()===1);
await page.locator('#open-recruitment').click();
const recruit=await closeTips();check('army and recruit tips',recruit.includes('army')&&recruit.includes('recruit'),recruit.join(','));
await page.locator('[data-subtab="map"]').click();
check('map tip not repeated',await page.locator('.tip-layer').count()===0);
await page.locator('[data-world="10,8"]').click();
await page.waitForFunction(()=>document.querySelector('.location-panel h3')?.textContent?.includes('斷雁寨'));await page.waitForTimeout(200);
await closeTips();
const foe=await page.locator('[data-place-role="battle"]').count();
check('battle sites marked',foe>=1,String(foe));
await page.screenshot({path:'artifacts/title-map-markers.png'});
await page.reload();
await page.locator('#title-continue').waitFor();
check('continue offered after autosave',true);
await page.locator('#title-continue').click();
await page.locator('.journey-header').waitFor();await page.waitForTimeout(300);
check('resume keeps hero',(await page.locator('.journey-header').textContent()).includes('豪俠'));
check('tips stay dismissed after reload',await page.locator('.tip-layer').count()===0);
const mobile=await browser.newPage({viewport:{width:390,height:844}});
await mobile.goto(url);await mobile.locator('#title-new').click();await mobile.locator('#story-skip').click();
check('mobile select has no horizontal scroll',await mobile.evaluate(()=>{const s=document.querySelector('.title-screen');return s.scrollWidth<=s.clientWidth+1;}));
await mobile.screenshot({path:'artifacts/title-mobile-select.png'});
const failed=checks.filter(c=>!c.ok);
await writeFile('artifacts/title-verification.json',JSON.stringify({url,checks,errors},null,2));
await browser.close();
if(failed.length||errors.length){console.error(JSON.stringify({failed,errors},null,2));process.exit(1);}
console.log(`PASS: ${checks.length} title/tip/marker checks`);
