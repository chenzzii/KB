import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
// v1.3.1: archers shoot distant enemies by clicking them; victory and bounty claims show a report.
const url=process.env.SMOKE_URL||'http://127.0.0.1:5173/';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
const check=(name,ok,detail='')=>{checks.push({name,ok:!!ok,detail});if(!ok)console.error('FAIL',name,detail);};
await mkdir('artifacts',{recursive:true});
await page.addInitScript(()=>localStorage.setItem('jiuzhou-settings',JSON.stringify({tips:false,music:false,sfx:false})));
await page.goto(url);
await page.locator('#title-new').click();await page.locator('#story-skip').click();await page.locator('[data-hero="wu_jiang"]').click();await page.locator('#title-start').click();
await page.locator('[data-action="accept"]').click();
await page.locator('[data-destination="7,5"]').click();await page.waitForFunction(()=>document.querySelector('.location-panel h3')?.textContent==='柳灣鄉營');
await page.locator('[data-world="11,12"]').click();await page.waitForFunction(()=>document.querySelector('.location-panel h3')?.textContent?.includes('朱三刀'),null,{timeout:20000});
await page.locator('[data-action="fight"]').click();await page.locator('.campaign-board').waitFor();
check('default attack mode is auto',await page.locator('#campaign-attack').inputValue()==='auto');
const archer=await page.locator('.battle-layout .company',{hasText:'羽林弓手'}).getAttribute('data-company');
await page.locator(`[data-company="${archer}"]`).click();
check('archer range note',(await page.locator('.range-note').textContent()).includes('可遠射'));
const targets=await page.locator('.cell.target-ranged-attack').evaluateAll(els=>els.map(e=>e.dataset.battleCell));
check('distant enemies marked for ranged',targets.length>=1,targets.join(' '));
await page.locator(`[data-battle-cell="${targets[0]}"]`).click();
await page.waitForFunction(()=>document.querySelector('.event-panel')?.textContent?.includes('遠射'));
check('archer shot without changing dropdown',(await page.locator('#message').textContent())==='');
const melee=await page.locator('.battle-layout .company',{hasText:'鄉勇'}).getAttribute('data-company');
await page.locator(`[data-company="${melee}"]`).click();
await page.locator('.campaign-board .cell.enemy').first().click();
check('melee unit far away gets a clear message',(await page.locator('#message').textContent()).includes('沒有遠射能力'));
await page.locator('#campaign-auto').click();
await page.locator('.report-layer[data-report="victory"]').waitFor({timeout:120000});
const victory=await page.locator('.report-card').innerText();
check('victory report lists bounty',victory.includes('討伐憑證')&&victory.includes('1,200 兩'),victory);
check('victory report lists leadership and seal',victory.includes('統率 100 → 200')&&victory.includes('山印'),victory);
check('victory report lists casualties',victory.includes('我方傷亡')&&victory.includes('殲滅敵軍'),victory);
await page.screenshot({path:'artifacts/battle-victory-report.png'});
await page.locator('#report-ok').click();
check('report closes',await page.locator('.report-layer').count()===0);
await page.locator('[data-destination="4,5"]').click();await page.waitForFunction(()=>document.querySelector('.location-panel h3')?.textContent==='青禾府',null,{timeout:20000});
await page.locator('[data-action="claim"]').click();
const claim=await page.locator('.report-layer[data-report="claim"] .report-card').innerText();
check('claim report shows gold',claim.includes('+1,200 兩')&&claim.includes('7,500 → 8,700'),claim);
await page.locator('#report-ok').click();
check('gold updated',(await page.locator('.journey-stats').innerText()).includes('8,700'));
await writeFile('artifacts/battle-report-verification.json',JSON.stringify({url,checks,errors},null,2));
await browser.close();
const failed=checks.filter(c=>!c.ok);
if(failed.length||errors.length){console.error(JSON.stringify({failed,errors},null,2));process.exit(1);}
console.log(`PASS: ${checks.length} ranged-attack and battle-report checks`);
